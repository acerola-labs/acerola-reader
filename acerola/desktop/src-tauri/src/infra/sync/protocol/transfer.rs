/// Publishes/fetches a chapter's bytes via `P2pBlobStore` (BLAKE3, automatic dedup and
/// verification), independent of the control stream (`FramedReader`/`FramedWriter`) that only
/// carries the `FileHeader` with the hash. A trait (instead of `Arc<BlobContext>` directly) only to keep
/// the `send_files`/`receive_files` tests free of a real iroh `Endpoint` —
/// `BlobChapterTransfer` is the only implementation used in production.
// Same case as `NetworkServiceApi`: `#[must_use]` generated by `#[async_trait]` on a
// return type that is already `must_use` (clippy >= 1.99, `double_must_use`).
#[allow(clippy::double_must_use)]
#[async_trait]
pub trait ChapterTransfer: Send + Sync {
    async fn publish(&self, bytes: Vec<u8>) -> Result<String, P2pError>;

    async fn fetch_reader(
        &self, blob_hash: &str, peer: &PeerIdentity,
    ) -> Result<Box<dyn AsyncRead + Send + Unpin>, P2pError>;

    /// RTT measured with `peer` right now, only used to size how many chapters to fetch in
    /// parallel in `receive_files` (see the docs there) — `None` when it cannot be measured (no live
    /// connection, or a test implementation that does not simulate a real network) falls back to the
    /// minimum parallelism, never to an error.
    async fn latency(&self, peer: &PeerIdentity) -> Option<std::time::Duration>;
}

pub struct BlobChapterTransfer {
    context: Arc<BlobContext>,
}

impl BlobChapterTransfer {
    pub fn new(context: Arc<BlobContext>) -> Self {
        Self { context }
    }
}

#[async_trait]
impl ChapterTransfer for BlobChapterTransfer {
    async fn publish(&self, bytes: Vec<u8>) -> Result<String, P2pError> {
        let store = self.context.blob_store().await?;
        // `P2pBlobStore::put` already returns `ConnectionError` (= `P2pError`, same type — see
        // `acerola_p2p::api::error`) — without the `.map_err(|err| P2pError::StreamFailed(err.to_string()))`
        // that used to be here, `?` propagates the real variant (`Timeout`,
        // `PeerDisconnected`, etc.) straight to the caller. Re-wrapping everything in `StreamFailed`
        // flattened this classification, already fixed at the source (see `classify_get_error` in
        // `lib/p2p/src/infra/error/iroh_blobs.rs`), back into raw text, forcing whoever
        // consumed this error to guess the cause by substring matching on `to_string()`.
        let hash = store.put(bytes).await?;
        Ok(hash.to_string())
    }

    async fn fetch_reader(
        &self, blob_hash: &str, peer: &PeerIdentity,
    ) -> Result<Box<dyn AsyncRead + Send + Unpin>, P2pError> {
        let store = self.context.blob_store().await?;
        // The hash format is local/static (does not come from the network) — it has no counterpart in
        // `ConnectionError` other than the generic `StreamFailed`, so `.map_err` is kept only here.
        let hash = blob_hash
            .parse()
            .map_err(|_| P2pError::StreamFailed(format!("invalid blob hash: {blob_hash}")))?;
        let addr = self.context.resolve_addr(peer).await?;

        // See the comment in `publish` — `fetch`/`get` already return a structured `ConnectionError`,
        // propagate it directly instead of flattening it into `StreamFailed(err.to_string())`.
        store.fetch(&hash, &addr).await?;
        store.get(&hash).await
    }

    async fn latency(&self, peer: &PeerIdentity) -> Option<std::time::Duration> {
        self.context.latency(peer).await
    }
}

/// Rejection text used both in the local event (`emit_busy`) and in the `SessionBusy` message
/// written to the wire (`write_session_busy`) — same reason in both places. Shared between
/// `acerola/sync-files/1` and `acerola/sync-comic/1`: both compete for the same
/// `FileSyncSessionGuard` per peer (see `file_session_guard.rs`).
pub const SESSION_BUSY_REASON: &str = "file sync session already in progress for this peer";

/// Value of the `error` field in `SessionBusy` — the same literal used by Android
/// (`protocol/files/exchange.rs::SESSION_BUSY_TAG`), it is what both sides use to recognize
/// this specific message instead of a regular `FileManifest`.
pub(super) const SESSION_BUSY_TAG: &str = "busy";

/// Reason used when the outbound side of a pre-scoped sync (`sync-comic`,
/// `browse-cover`) triggers the connection without having registered the local intent first — only happens if
/// the Tauri command forgot to populate the registry (`PendingComicSyncRegistry`/
/// `PendingCoverRequestRegistry`) before calling `connect()`. Shared between both
/// handlers for the same reason as `SESSION_BUSY_REASON`: a string of ours recognized by
/// exact equality in `classify_sync_error`, not a heuristic on third-party text — and
/// shared between both sites so they do not diverge (each handler used to have its own
/// phrase, none of them classified, so the UI always showed the raw English text).
pub const NO_PENDING_SCOPE_REASON: &str = "no pending sync scope registered for this peer";

/// Reason used when the inbound of `acerola/sync-history-entry/1` answers `comic_known:
/// false` in the `HistoryEntryAck` — the outbound treats this as a failure (not silent success),
/// since no entry/marker could be applied on the other side. Same technique as
/// `NO_PENDING_SCOPE_REASON`: a string of ours recognized by exact equality, not a heuristic.
pub const PEER_COMIC_NOT_FOUND_REASON: &str = "peer does not have this comic";

/// Stable identifier of a sync error cause, serialized in `snake_case` (`"busy"`,
/// `"timeout"`, `"connection_lost"`) — the same value the frontend already expected when this was
/// a loose `&'static str`, so switching to an enum does not change the wire contract (`SYNC_ERROR_MESSAGES`
/// in `use-network-sync.svelte.ts` stays the same). The advantage of the enum is that the `match` in
/// `classify_sync_error` is exhaustive and checked at compile time — without it, each new cause
/// was "just another `.contains()`" testing arbitrary text from an external lib, fragile (breaks
/// if the message changes) and with no guarantee of covering the real cases.
#[derive(Debug, Clone, Copy, PartialEq, Eq, serde::Serialize)]
#[serde(rename_all = "snake_case")]
pub(super) enum SyncErrorCode {
    Busy,
    Timeout,
    ConnectionLost,
    PeerNotFound,
    AuthDenied,
    Shutdown,
    IncompatibleVersion,
    StartupFailed,
    BlobNotFound,
    /// Header received without `blob_hash` — should not happen (protocol bug, not a network
    /// failure), but it still needs a translatable code instead of falling back to raw text.
    MissingBlobHash,
    /// Generic fallback for a `ChapterTransfer::fetch_reader` failure when the underlying
    /// `P2pError` is none of the specific causes already covered above.
    BlobFetchFailed,
    ChecksumMismatch,
    ComicDirectoryUnavailable,
    PersistFailed,
    NoPendingRequest,
    /// The peer answered that it does not have the referenced comic (`HistoryEntryAck.comic_known ==
    /// false`) — history never creates a new comic on the destination, so this is expected when the
    /// other side has not synced that comic's files yet.
    ComicNotFound,
    /// The session ended without a protocol error, but not every item arrived (see the docs of
    /// `receive_files`/`receive_extras`) — previously these two occurrences (`comic_handler.rs`,
    /// `file_handler.rs`) built the message in pt-BR directly in the backend, without any
    /// `code`: it broke the typed-error rule in two ways at once (fixed text in a
    /// language Y decided by the backend, AND no translation at all for the frontend to use).
    PartialSync,
}

/// Classifies a `P2pError` (not its text) into a `SyncErrorCode` the frontend translates via
/// Paraglide (`SYNC_ERROR_MESSAGES` in `use-network-sync.svelte.ts`). This is only reliably
/// possible because `ChapterTransfer::publish`/`fetch_reader` (`BlobChapterTransfer`, right
/// above) stopped flattening `ConnectionError` into `StreamFailed(err.to_string())` — the error that
/// reaches here is already the real variant `lib/p2p` classified at the source
/// (`classify_connection_error`/`classify_get_error`, see `infra/error/{iroh,iroh_blobs}.rs` in the
/// `acerola-p2p` crate), not text to guess via substring matching. `Busy` remains the
/// exception: it is not a `ConnectionError` variant (it is a concept of this sync protocol, not
/// of the transport), so the only way to recognize it through `Handler::handle`'s fixed
/// `Result<(), P2pError>` is the text THIS MODULE controls (`SESSION_BUSY_REASON`) — exact
/// equality on a constant of ours, not a heuristic over third-party text.
pub(super) fn classify_sync_error(error: &P2pError) -> Option<SyncErrorCode> {
    match error {
        P2pError::Timeout => Some(SyncErrorCode::Timeout),
        P2pError::PeerDisconnected(_) => Some(SyncErrorCode::ConnectionLost),
        P2pError::StreamFailed(msg) if msg.contains(SESSION_BUSY_REASON) => {
            Some(SyncErrorCode::Busy)
        },
        P2pError::StreamFailed(msg) if msg == NO_PENDING_SCOPE_REASON => {
            Some(SyncErrorCode::NoPendingRequest)
        },
        P2pError::StreamFailed(msg) if msg == PEER_COMIC_NOT_FOUND_REASON => {
            Some(SyncErrorCode::ComicNotFound)
        },
        // The rest of `StreamFailed` is generic low-level I/O text (framing, disk) without
        // a specific cause to name — it falls back to the caller's fallback (raw `message` in the
        // backend log, which is never shown as is in the UI).
        P2pError::StreamFailed(_) => None,
        P2pError::PeerNotFound(_) => Some(SyncErrorCode::PeerNotFound),
        P2pError::AuthDenied(_) => Some(SyncErrorCode::AuthDenied),
        P2pError::Shutdown => Some(SyncErrorCode::Shutdown),
        P2pError::IncompatibleVersion => Some(SyncErrorCode::IncompatibleVersion),
        P2pError::StartupFailed(_) => Some(SyncErrorCode::StartupFailed),
        P2pError::BlobNotFound(_) => Some(SyncErrorCode::BlobNotFound),
    }
}

/// Emitted when `FileSyncSessionGuard` refuses a session because there is already an active one for
/// the same peer — reuses the `sync:files:error` event already handled by the frontend instead of
/// introducing a new event (see `use-network-sync.svelte.ts::parseErrorPayload`). The caller
/// passes the event name (`sync:files:error` or `sync:comic:error`) because each protocol has
/// its own channel. `message` stays in English (it is technical log/wire text, it must not be
/// shown as is) — `code` is the stable identifier the frontend uses to translate via
/// Paraglide (`tauriErrors.sync.sessionBusy.label`), following the same pattern as `errors.i18n.ts`.
pub fn emit_busy(emit: &EventEmitter, event_name: &str, peer_id: &str) {
    (emit)(
        event_name,
        sync_error_payload(peer_id, SESSION_BUSY_REASON, Some(SyncErrorCode::Busy), None),
    );
}

/// Builds the `sync:*:error` JSON used both by `emit_busy` and by the generic `Err(error)` branch
/// of `FileSyncOutbound`/`FileSyncInbound`/`ComicSyncOutbound`/`ComicSyncInbound`
/// (`file_handler.rs`/`comic_handler.rs`) — a single place for the payload shape instead of 5
/// near-identical scattered `serde_json::json!({...})`, which already diverged from each other (not all
/// included `comicName`). `code: None` serializes as `null` — the frontend treats that as "no
/// known translation, show the raw `message`" (`translateSyncMessage`).
pub(super) fn sync_error_payload(
    peer_id: &str, message: &str, code: Option<SyncErrorCode>, comic_name: Option<&str>,
) -> String {
    serde_json::json!({
        "peerId": peer_id,
        "message": message,
        "code": code,
        "comicName": comic_name,
    })
    .to_string()
}

/// Variant of `sync_error_payload` for the 5 PER-ITEM failure points in `receive_files`/
/// `receive_extras` (blob not found, fetch failed, checksum mismatch, folder unavailable,
/// persistence failed) — all non-fatal: the item is skipped (`skipped += 1`) and the loop moves on
/// to the next chapter/extra, the whole session does not abort.
///
/// Without `"itemLevel": true` + `"item"` here, the frontend had no way to tell these events
/// apart from a real session error (`Err(error)` in `handle()`, or `PartialSync`) — both
/// carry the same `peerId`, so `use-network-sync.svelte.ts` correlated ANY
/// `sync:files:error`/`sync:comic:error` with that peer's in-progress "started"/"progress" row
/// and marked it as terminal — a 20-chapter session with 1 checksum mismatch in the middle
/// showed "error" on screen even while continuing (and completing) normally afterwards. Android already
/// solved this on its side with an equivalent sentinel (empty `comicName`/`chapter` =
/// whole-session failure, see `protocol::files::run_and_report` in the native crate) — this helper
/// brings the same contract to Desktop, explicit instead of inferred from a silent sentinel.
pub(super) fn item_error_payload(
    peer_id: &str, message: &str, code: Option<SyncErrorCode>, comic_name: &str, item: &str,
) -> String {
    serde_json::json!({
        "peerId": peer_id,
        "message": message,
        "code": code,
        "comicName": comic_name,
        "item": item,
        "itemLevel": true,
    })
    .to_string()
}

/// Writes the session rejection message directly to the stream, instead of the manifest —
/// used when `FileSyncSessionGuard::try_acquire` already blocked the session in `handle()`, before
/// the rest of the protocol runs. Takes the raw `send` (not an already built `FramedWriter`) because that is
/// exactly the state `handle()` is in at the time of the rejection: the stream has not been
/// wrapped in any framing yet. Best-effort: if the write fails (peer already dropped, stream already
/// closed), it is ignored — the session was already rejected locally anyway.
pub async fn write_session_busy(send: Box<dyn AsyncWrite + Send + Unpin>) {
    let mut writer = framed_writer(send);
    let _ = write_json(
        &mut writer,
        &SessionBusy {
            error: SESSION_BUSY_TAG.to_string(),
            reason: SESSION_BUSY_REASON.to_string(),
        },
    )
    .await;
}

/// Reads the peer's first message, which can be either the expected message (`T`: a whole
/// `FileManifest` or one scoped to a single comic — see `FileSyncService::build_manifest_for_comic`
/// — or `ComicSyncRequest` in the `acerola/sync-comic/1` protocol) or a `SessionBusy`
/// rejection — with no enum tag on the wire (same convention as the rest of the protocol), the only
/// way to know which is to peek at the raw JSON before deciding the concrete type. Only the
/// initial read point(s) in each `run()` use this: after the first message, an accepted
/// session never sends `SessionBusy` again.
pub async fn read_or_busy<T: DeserializeOwned>(reader: &mut FramedReader) -> Result<T, P2pError> {
    let value: serde_json::Value = read_json(reader).await?;

    let is_busy = value.get("error").and_then(|tag| tag.as_str()) == Some(SESSION_BUSY_TAG);
    if is_busy {
        let reason = value.get("reason").and_then(|r| r.as_str()).unwrap_or("peer is busy");
        return Err(P2pError::StreamFailed(format!("peer busy: {reason}")));
    }

    serde_json::from_value(value).map_err(|err| RpcError::Deserialize(err.to_string()).into())
}

/// Sends, in sequence, the files in `wanted` (what the peer requested from us). If an item no
/// longer exists locally (race with a concurrent deletion), sends an "unavailable" header
/// (`size: 0`) instead of aborting the whole session. The bytes no longer travel
/// over the control stream — they are published to the local blob store (`ChapterTransfer::publish`) and the
/// resulting hash goes in the `FileHeader`; the receiver fetches on demand via `fetch_reader`.
///
/// Returns how many items of `wanted` were NOT actually sent (file disappeared locally
/// between the want-list and the send) — the caller uses this count to decide whether the session can
/// really be reported as "complete" to the user (see `ComicSyncOutbound`/`FileSyncOutbound`).
pub async fn send_files(
    writer: &mut FramedWriter, wanted: &[(String, String)], service: &FileSyncService,
    emit: &EventEmitter, progress_event: &str, transfer: &Arc<dyn ChapterTransfer>,
) -> Result<usize, P2pError> {
    let mut skipped = 0usize;

    for (comic_name, chapter) in wanted {
        let resolved = service.resolve_local_file(comic_name, chapter).await?;

        let Some((path, size, checksum, file_name)) = resolved else {
            tracing::warn!(
                comic_name = %comic_name,
                chapter = %chapter,
                "[FileSync] requested file no longer exists locally — sending unavailable header"
            );
            skipped += 1;
            write_json(
                writer,
                &FileHeader {
                    comic_name: comic_name.clone(),
                    chapter: chapter.clone(),
                    file_name: String::new(),
                    size: 0,
                    checksum: None,
                    blob_hash: None,
                },
            )
            .await?;
            continue;
        };

        let bytes = tokio::fs::read(&path).await.map_err(RpcError::from)?;
        let blob_hash = transfer.publish(bytes).await?;

        write_json(
            writer,
            &FileHeader {
                comic_name: comic_name.clone(),
                chapter: chapter.clone(),
                file_name,
                size,
                checksum,
                blob_hash: Some(blob_hash),
            },
        )
        .await?;

        (emit)(progress_event, format!("{} - {}", comic_name, chapter));
    }

    Ok(skipped)
}

/// How many chapters to fetch in parallel, based on the RTT measured RIGHT NOW with the peer (see
/// `ChapterTransfer::latency`) — a slow link (distant relay) needs several fetches "in
/// flight" at the same time so it does not sit idle between one round-trip and the next; a local link
/// (mDNS/LAN) already saturates with very little parallelism, and more than that just wastes memory.
/// Fixed cap of 6 on purpose: an unbounded burst of fetches (`fetchCoversFor`, in the
/// frontend) was exactly what degraded a real connection to the point where a file sync
/// took minutes, chapter by chapter — there is no point solving "too slow"
/// by recreating "so fast it breaks" for the same peer. Without a measurement (peer has not
/// answered any ping yet, or a test implementation) it falls back to the most conservative of the three — not
/// worth risking parallelism over a connection of unknown health.
fn chapter_fetch_concurrency(latency: Option<std::time::Duration>) -> usize {
    match latency {
        Some(rtt) if rtt <= std::time::Duration::from_millis(20) => 2,
        Some(rtt) if rtt <= std::time::Duration::from_millis(200) => 4,
        Some(_) => 6,
        None => 2,
    }
}

/// How many permits to take out of the pool (`Semaphore::forget_permits`) the first time a fetch
/// hits the inactivity timeout in a session — halves it, never below 1 (never
/// turns parallelism off completely, only reduces it). Computed from the ORIGINAL N
/// (`initial_permits` in `receive_files`), not from `available_permits()` in real time: at the
/// moment of the first timeout most of the original N is already in use by in-flight fetches, so
/// `available_permits()` only reflects the leftover and would underestimate the cut.
fn permits_to_forget(initial_permits: usize) -> usize {
    initial_permits.saturating_sub((initial_permits / 2).max(1))
}

/// Result of processing ONE header already read from the wire — extracted from `receive_files` so it can
/// run as an independent task (`tokio::spawn`), in parallel with reading the NEXT
/// header, instead of blocking the whole loop on fetching a single chapter at a time.
enum ChapterOutcome {
    Persisted,
    /// `timed_out: true` only when the specific reason for skipping this item was
    /// `P2pError::Timeout` on the blob fetch — the only signal `receive_files` uses to reduce
    /// parallelism for the rest of the session (see the docs there). The other skip reasons (missing
    /// blob_hash, checksum, folder unavailable, persistence failure, failure reading the already
    /// fetched blob locally) do not indicate a degraded connection, just an isolated bad item — it makes
    /// no sense for them to trigger the backoff.
    Skipped {
        timed_out: bool,
    },
}

#[allow(clippy::too_many_arguments)]
async fn receive_one_chapter(
    header: FileHeader, service: FileSyncService, emit: EventEmitter, progress_event: String,
    error_event: String, peer: PeerIdentity, transfer: Arc<dyn ChapterTransfer>,
) -> ChapterOutcome {
    if header.size == 0 {
        tracing::warn!(
            comic_name = %header.comic_name,
            chapter = %header.chapter,
            "[FileSync] peer reported chapter as unavailable (size=0) — skipping"
        );
        return ChapterOutcome::Skipped { timed_out: false };
    }

    let Some(blob_hash) = header.blob_hash.as_deref() else {
        tracing::warn!(
            comic_name = %header.comic_name,
            chapter = %header.chapter,
            "[FileSync] header missing blob_hash — skipping"
        );
        (emit)(
            &error_event,
            item_error_payload(
                &peer.id,
                "missing blob hash",
                Some(SyncErrorCode::MissingBlobHash),
                &header.comic_name,
                &header.chapter,
            ),
        );
        return ChapterOutcome::Skipped { timed_out: false };
    };

    let mut blob_reader = match transfer.fetch_reader(blob_hash, &peer).await {
        Ok(reader) => reader,
        Err(err) => {
            tracing::warn!(
                comic_name = %header.comic_name,
                chapter = %header.chapter,
                error = %err,
                "[FileSync] failed to fetch chapter blob — skipping"
            );
            let timed_out = matches!(err, P2pError::Timeout);
            (emit)(
                &error_event,
                item_error_payload(
                    &peer.id,
                    &format!("blob fetch failed: {err}"),
                    Some(classify_sync_error(&err).unwrap_or(SyncErrorCode::BlobFetchFailed)),
                    &header.comic_name,
                    &header.chapter,
                ),
            );
            return ChapterOutcome::Skipped { timed_out };
        },
    };

    // It used to use `?` and abort the WHOLE session — unlike the other failure points of this
    // function, which were all already non-fatal. This read is local (`P2pBlobStore::get`, disk/
    // cache already filled by `fetch` a few milliseconds earlier), not a second network
    // round: a failure here says nothing about the health of the connection nor of the rest of the header
    // stream, so treating it as just another skipped item (instead of fatal) aligns this last exception
    // with the philosophy already established in the rest of the function.
    let mut bytes = Vec::new();
    if let Err(err) = blob_reader.read_to_end(&mut bytes).await {
        tracing::warn!(
            comic_name = %header.comic_name,
            chapter = %header.chapter,
            error = %err,
            "[FileSync] failed to read fetched chapter blob — skipping"
        );
        (emit)(
            &error_event,
            item_error_payload(
                &peer.id,
                &format!("failed to read chapter blob: {err}"),
                None,
                &header.comic_name,
                &header.chapter,
            ),
        );
        return ChapterOutcome::Skipped { timed_out: false };
    }

    let (bytes, computed_checksum) = match tokio::task::spawn_blocking(move || {
        use sha2::{Digest, Sha256};
        let hash = format!("{:x}", Sha256::digest(&bytes));
        (bytes, hash)
    })
    .await
    {
        Ok(result) => result,
        Err(err) => {
            tracing::warn!(error = %err, "[FileSync] hashing task panicked");
            return ChapterOutcome::Skipped { timed_out: false };
        },
    };

    if let Some(expected) = &header.checksum {
        if expected != &computed_checksum {
            tracing::warn!(
                comic_name = %header.comic_name,
                chapter = %header.chapter,
                expected = %expected,
                computed = %computed_checksum,
                "[FileSync] checksum mismatch — skipping"
            );
            (emit)(
                &error_event,
                item_error_payload(
                    &peer.id,
                    "checksum mismatch",
                    Some(SyncErrorCode::ChecksumMismatch),
                    &header.comic_name,
                    &header.chapter,
                ),
            );
            return ChapterOutcome::Skipped { timed_out: false };
        }
    }

    // Resolves the comic folder BEFORE writing the temporary file — writes it already in the
    // final destination (the same folder `persist_received_chapter` will use for the rename),
    // without a separate staging folder that was left visible in the user's library.
    let comic_dir = match service.resolve_comic_dir(&header.comic_name).await {
        Ok(comic) => std::path::PathBuf::from(comic.path),
        Err(err) => {
            tracing::warn!(
                comic_name = %header.comic_name,
                chapter = %header.chapter,
                error = %err,
                "[FileSync] failed to resolve comic directory — skipping"
            );
            (emit)(
                &error_event,
                item_error_payload(
                    &peer.id,
                    "failed to resolve comic directory",
                    Some(SyncErrorCode::ComicDirectoryUnavailable),
                    &header.comic_name,
                    &header.chapter,
                ),
            );
            return ChapterOutcome::Skipped { timed_out: false };
        },
    };
    let temp_path = comic_dir.join(format!(".incoming-{}.tmp", rand::random::<u64>()));
    if let Err(err) = tokio::fs::write(&temp_path, &bytes).await {
        tracing::warn!(
            comic_name = %header.comic_name,
            chapter = %header.chapter,
            error = %err,
            "[FileSync] failed to write temp file for received chapter — skipping"
        );
        (emit)(
            &error_event,
            item_error_payload(
                &peer.id,
                &format!("failed to write temp file: {}", RpcError::from(err)),
                Some(SyncErrorCode::PersistFailed),
                &header.comic_name,
                &header.chapter,
            ),
        );
        return ChapterOutcome::Skipped { timed_out: false };
    }

    if let Err(err) = service
        .persist_received_chapter(
            &header.comic_name,
            &header.chapter,
            &header.file_name,
            &temp_path,
            computed_checksum,
        )
        .await
    {
        tracing::warn!(
            comic_name = %header.comic_name,
            chapter = %header.chapter,
            error = %err,
            "[FileSync] failed to persist received chapter — skipping"
        );
        (emit)(
            &error_event,
            item_error_payload(
                &peer.id,
                &format!("failed to persist chapter: {err}"),
                Some(SyncErrorCode::PersistFailed),
                &header.comic_name,
                &header.chapter,
            ),
        );
        return ChapterOutcome::Skipped { timed_out: false };
    }

    (emit)(&progress_event, format!("{} - {}", header.comic_name, header.chapter));
    ChapterOutcome::Persisted
}

/// Receives, in sequence, `expected_count` files: each `FileHeader` carries a `blob_hash` instead
/// of raw bytes on the stream — fetches via `ChapterTransfer::fetch_reader` (which already verifies
/// integrity via BLAKE3 before returning the reader), writes to a temporary file and moves it to the
/// final destination after checking the legacy SHA-256 against the one announced in the header (continuity
/// of the existing history/telemetry, redundant with the blob store verification but cheap
/// enough to keep).
///
/// Discards "unavailable" headers (`size: 0`), blob fetch/read failures or checksum
/// mismatches without aborting the whole session — each case logs via `tracing` and is counted in the
/// return value (`usize` = how many chapters of `expected_count` were NOT persisted). Bug
/// reported on 2026-08-22: a 2-chapter sync persisted only 1, with no visible error in the
/// log — because these item failures never logged anything, they only emitted an event to the frontend, and the
/// whole session was still reported as "complete" to the caller (`ComicSyncOutbound`/
/// `FileSyncOutbound`) even with missing items.
///
/// `#[allow(too_many_arguments)]`: pre-existing technical debt (there were already 8 parameters before
/// this change) — grouping them in a context struct is a bigger refactor, out of the scope of the
/// bug that motivated this function to change.
///
/// Each header is read in sequence from the wire (it is a single ordered stream, header 2 cannot be read
/// before 1) but the FETCH of the blob it references runs in its own task, in a pool of up to
/// `chapter_fetch_concurrency(...)` concurrent chapters — before that, the loop blocked on the
/// whole fetch of ONE chapter before even reading the next header, so any per-item
/// slowness (high RTT, degraded connection) became total session time 1:1, with no chance to
/// overlap a slow fetch with the next one while it is still in flight. Motivated by a real sync
/// that took minutes over a relay connection with ~1s RTT, one chapter at a time.
#[allow(clippy::too_many_arguments)]
pub async fn receive_files(
    reader: &mut FramedReader, expected_count: usize, service: &FileSyncService,
    emit: &EventEmitter, progress_event: &str, error_event: &str, peer: &PeerIdentity,
    transfer: &Arc<dyn ChapterTransfer>,
) -> Result<usize, P2pError> {
    let initial_permits = chapter_fetch_concurrency(transfer.latency(peer).await);
    let semaphore = Arc::new(Semaphore::new(initial_permits));
    // `backed_off` ensures the `permits_to_forget` cut only fires once per session —
    // see the docs of `permits_to_forget` for why it is computed that way.
    let backed_off = Arc::new(AtomicBool::new(false));
    let permits_to_forget_on_timeout = permits_to_forget(initial_permits);

    let mut tasks = JoinSet::new();
    let mut skipped = 0usize;

    for _ in 0..expected_count {
        let header: FileHeader = read_json(reader).await?;

        tracing::debug!(
            comic_name = %header.comic_name,
            chapter = %header.chapter,
            file_name = %header.file_name,
            "[FileSync] header received from the wire"
        );

        let permit = Arc::clone(&semaphore)
            .acquire_owned()
            .await
            .expect("semaphore is never closed while receive_files is running");
        let semaphore_for_backoff = Arc::clone(&semaphore);
        let backed_off = Arc::clone(&backed_off);
        let task_service = service.clone();
        let task_emit = Arc::clone(emit);
        let task_progress_event = progress_event.to_string();
        let task_error_event = error_event.to_string();
        let task_peer = peer.clone();
        let task_transfer = Arc::clone(transfer);

        tasks.spawn(async move {
            let _permit = permit;
            let outcome = receive_one_chapter(
                header,
                task_service,
                task_emit,
                task_progress_event,
                task_error_event,
                task_peer,
                task_transfer,
            )
            .await;

            if matches!(outcome, ChapterOutcome::Skipped { timed_out: true })
                && backed_off
                    .compare_exchange(false, true, Ordering::SeqCst, Ordering::SeqCst)
                    .is_ok()
                && permits_to_forget_on_timeout > 0
            {
                semaphore_for_backoff.forget_permits(permits_to_forget_on_timeout);
            }

            outcome
        });
    }

    while let Some(result) = tasks.join_next().await {
        match result {
            Ok(ChapterOutcome::Persisted) => {},
            Ok(ChapterOutcome::Skipped { .. }) => skipped += 1,
            // Only lands here if the task itself panicked (a real bug, not a network/protocol error) —
            // no branch of `receive_one_chapter` propagates an error, it only returns the enum. Counts as
            // skipped instead of aborting the rest of the session because of ONE item.
            Err(join_err) => {
                tracing::error!(error = %join_err, "[FileSync] chapter fetch task panicked — skipping");
                skipped += 1;
            },
        }
    }

    Ok(skipped)
}

/// Sends, in sequence, the extra items (cover/banner/`ComicInfo.xml`) of `wanted_extras` — same
/// logic as `send_files`, but via `FileSyncService::resolve_local_extra`/`FileExtraHeader`
/// instead of chapters.
pub async fn send_extras(
    writer: &mut FramedWriter, wanted_extras: &[(String, String)], service: &FileSyncService,
    emit: &EventEmitter, progress_event: &str, transfer: &Arc<dyn ChapterTransfer>,
) -> Result<usize, P2pError> {
    let mut skipped = 0usize;

    for (comic_name, kind) in wanted_extras {
        let resolved = service.resolve_local_extra(comic_name, kind).await?;

        let Some((path, size, checksum, file_name)) = resolved else {
            tracing::warn!(
                comic_name = %comic_name,
                kind = %kind,
                "[FileSync] requested extra no longer exists locally — sending unavailable header"
            );
            skipped += 1;
            write_json(
                writer,
                &FileExtraHeader {
                    comic_name: comic_name.clone(),
                    kind: kind.clone(),
                    file_name: String::new(),
                    size: 0,
                    checksum: None,
                    blob_hash: None,
                },
            )
            .await?;
            continue;
        };

        let bytes = tokio::fs::read(&path).await.map_err(RpcError::from)?;
        let blob_hash = transfer.publish(bytes).await?;

        write_json(
            writer,
            &FileExtraHeader {
                comic_name: comic_name.clone(),
                kind: kind.clone(),
                file_name,
                size,
                checksum,
                blob_hash: Some(blob_hash),
            },
        )
        .await?;

        (emit)(progress_event, format!("{} - {}", comic_name, kind));
    }

    Ok(skipped)
}

/// Receives, in sequence, `expected_count` extra items: same mechanics as `receive_files`
/// (fetch via blob store, write to a temporary file, verify checksum), but persisting via
/// `FileSyncService::persist_received_extra` instead of `persist_received_chapter` — it does not go to
/// `chapter_archive`, it goes to `comic_directory` (cover/banner) or becomes `ComicInfo.xml` at the root.
///
/// After persisting a `ComicInfo.xml`, triggers `MetadataService::sync_comic_comic_info`
/// (the same method used by the manual "sync via ComicInfo" button) to leave the
/// title/synopsis/author already updated in the database without user action — best-effort: a failure
/// here logs a warning and counts as an unsynced item in the stats, but does not take down the
/// session (the file itself was already transferred successfully).
#[allow(clippy::too_many_arguments)]
pub async fn receive_extras(
    reader: &mut FramedReader, expected_count: usize, service: &FileSyncService,
    metadata_service: &Arc<MetadataService>, emit: &EventEmitter, progress_event: &str,
    error_event: &str, peer: &PeerIdentity, transfer: &Arc<dyn ChapterTransfer>,
) -> Result<usize, P2pError> {
    let mut skipped = 0usize;

    for _ in 0..expected_count {
        let header: FileExtraHeader = read_json(reader).await?;

        if header.size == 0 {
            tracing::warn!(
                comic_name = %header.comic_name,
                kind = %header.kind,
                "[FileSync] peer reported extra as unavailable (size=0) — skipping"
            );
            skipped += 1;
            continue;
        }

        let Some(blob_hash) = header.blob_hash.as_deref() else {
            tracing::warn!(
                comic_name = %header.comic_name,
                kind = %header.kind,
                "[FileSync] extra header missing blob_hash — skipping"
            );
            skipped += 1;
            (emit)(
                error_event,
                item_error_payload(
                    &peer.id,
                    "missing blob hash",
                    Some(SyncErrorCode::MissingBlobHash),
                    &header.comic_name,
                    &header.kind,
                ),
            );
            continue;
        };

        let mut blob_reader = match transfer.fetch_reader(blob_hash, peer).await {
            Ok(reader) => reader,
            Err(err) => {
                tracing::warn!(
                    comic_name = %header.comic_name,
                    kind = %header.kind,
                    error = %err,
                    "[FileSync] failed to fetch extra blob — skipping"
                );
                skipped += 1;
                (emit)(
                    error_event,
                    item_error_payload(
                        &peer.id,
                        &format!("blob fetch failed: {err}"),
                        Some(classify_sync_error(&err).unwrap_or(SyncErrorCode::BlobFetchFailed)),
                        &header.comic_name,
                        &header.kind,
                    ),
                );
                continue;
            },
        };

        let mut bytes = Vec::new();
        blob_reader
            .read_to_end(&mut bytes)
            .await
            .map_err(|err| P2pError::StreamFailed(err.to_string()))?;

        let computed_checksum = {
            use sha2::{Digest, Sha256};
            format!("{:x}", Sha256::digest(&bytes))
        };

        if let Some(expected) = &header.checksum {
            if expected != &computed_checksum {
                tracing::warn!(
                    comic_name = %header.comic_name,
                    kind = %header.kind,
                    expected = %expected,
                    computed = %computed_checksum,
                    "[FileSync] extra checksum mismatch — skipping"
                );
                skipped += 1;
                (emit)(
                    error_event,
                    item_error_payload(
                        &peer.id,
                        "checksum mismatch",
                        Some(SyncErrorCode::ChecksumMismatch),
                        &header.comic_name,
                        &header.kind,
                    ),
                );
                continue;
            }
        }

        let comic_dir = match service.resolve_comic_dir(&header.comic_name).await {
            Ok(comic) => std::path::PathBuf::from(comic.path),
            Err(err) => {
                tracing::warn!(
                    comic_name = %header.comic_name,
                    kind = %header.kind,
                    error = %err,
                    "[FileSync] failed to resolve comic directory for extra — skipping"
                );
                skipped += 1;
                (emit)(
                    error_event,
                    item_error_payload(
                        &peer.id,
                        "failed to resolve comic directory",
                        Some(SyncErrorCode::ComicDirectoryUnavailable),
                        &header.comic_name,
                        &header.kind,
                    ),
                );
                continue;
            },
        };
        let temp_path = comic_dir.join(format!(".incoming-{}.tmp", rand::random::<u64>()));
        tokio::fs::write(&temp_path, &bytes).await.map_err(RpcError::from)?;

        let persisted = service
            .persist_received_extra(&header.comic_name, &header.kind, &header.file_name, &temp_path)
            .await;

        let comic = match persisted {
            Ok(comic) => comic,
            Err(err) => {
                tracing::warn!(
                    comic_name = %header.comic_name,
                    kind = %header.kind,
                    error = %err,
                    "[FileSync] failed to persist received extra — skipping"
                );
                skipped += 1;
                (emit)(
                    error_event,
                    item_error_payload(
                        &peer.id,
                        &format!("failed to persist extra: {err}"),
                        Some(SyncErrorCode::PersistFailed),
                        &header.comic_name,
                        &header.kind,
                    ),
                );
                continue;
            },
        };

        if header.kind == EXTRA_KIND_COMIC_INFO {
            if let Err(err) = metadata_service.sync_comic_comic_info(comic.id).await {
                tracing::warn!(
                    comic_name = %header.comic_name,
                    error = %err,
                    "[FileSync] ComicInfo.xml received, but metadata reprocessing failed"
                );
            }
        }

        (emit)(progress_event, format!("{} - {}", header.comic_name, header.kind));
    }

    Ok(skipped)
}

/// In-memory `ChapterTransfer` double for tests that do not have a real iroh `Endpoint`
/// (`BlobChapterTransfer`, used in production, needs one). `shared_pair()` returns two
/// handles pointing to the same internal `HashMap` — simulates both sides publishing/fetching on the
/// same content-addressed "network store".
#[cfg(test)]
pub struct InMemoryChapterTransfer {
    blobs: std::sync::Mutex<std::collections::HashMap<String, Vec<u8>>>,
    /// `None` by default (same meaning as "no real connection to measure" in the trait docs) —
    /// tests exercising latency-based parallelism sizing use
    /// `set_latency` to simulate a specific RTT without needing a real network.
    latency: std::sync::Mutex<Option<std::time::Duration>>,
}

#[cfg(test)]
impl InMemoryChapterTransfer {
    pub fn shared_pair() -> (Arc<dyn ChapterTransfer>, Arc<dyn ChapterTransfer>) {
        let shared = Arc::new(InMemoryChapterTransfer {
            blobs: std::sync::Mutex::new(std::collections::HashMap::new()),
            latency: std::sync::Mutex::new(None),
        });
        (Arc::clone(&shared) as Arc<dyn ChapterTransfer>, shared as Arc<dyn ChapterTransfer>)
    }

    pub fn set_latency(&self, latency: std::time::Duration) {
        *self.latency.lock().unwrap() = Some(latency);
    }
}

#[cfg(test)]
#[async_trait]
impl ChapterTransfer for InMemoryChapterTransfer {
    async fn publish(&self, bytes: Vec<u8>) -> Result<String, P2pError> {
        use sha2::{Digest, Sha256};
        let hash = format!("{:x}", Sha256::digest(&bytes));
        self.blobs.lock().unwrap().insert(hash.clone(), bytes);
        Ok(hash)
    }

    async fn fetch_reader(
        &self, blob_hash: &str, _peer: &PeerIdentity,
    ) -> Result<Box<dyn AsyncRead + Send + Unpin>, P2pError> {
        let bytes = self.blobs.lock().unwrap().get(blob_hash).cloned().ok_or_else(|| {
            P2pError::StreamFailed(format!("unknown blob hash in test transfer: {blob_hash}"))
        })?;

        // `tokio::io::duplex` already implements `AsyncRead`/`AsyncWrite` — simpler than
        // implementing a manual `poll_read` just for a test. Writes everything and closes (EOF) before
        // returning the read end.
        use tokio::io::AsyncWriteExt;
        let (mut writer, reader) = tokio::io::duplex(bytes.len().max(1));
        tokio::spawn(async move {
            let _ = writer.write_all(&bytes).await;
            let _ = writer.shutdown().await;
        });
        Ok(Box::new(reader))
    }

    async fn latency(&self, _peer: &PeerIdentity) -> Option<std::time::Duration> {
        *self.latency.lock().unwrap()
    }
}

#[cfg(test)]
mod concurrency_tests {
    use std::time::Duration;

    use super::*;

    #[test]
    fn chapter_fetch_concurrency_scales_with_measured_latency() {
        assert_eq!(chapter_fetch_concurrency(None), 2, "no measurement, most conservative");
        assert_eq!(chapter_fetch_concurrency(Some(Duration::from_millis(0))), 2);
        assert_eq!(
            chapter_fetch_concurrency(Some(Duration::from_millis(20))),
            2,
            "exact limit of the low step, still inside it"
        );
        assert_eq!(
            chapter_fetch_concurrency(Some(Duration::from_millis(21))),
            4,
            "1ms above the low step already goes up to the medium one"
        );
        assert_eq!(
            chapter_fetch_concurrency(Some(Duration::from_millis(200))),
            4,
            "exact limit of the medium step, still inside it"
        );
        assert_eq!(
            chapter_fetch_concurrency(Some(Duration::from_millis(201))),
            6,
            "1ms above the medium step already goes up to the cap"
        );
        assert_eq!(
            chapter_fetch_concurrency(Some(Duration::from_secs(2))),
            6,
            "very high RTT (bad relay) never goes above the cap of 6"
        );
    }

    #[test]
    fn permits_to_forget_halves_the_pool_but_never_below_one_permit_left() {
        assert_eq!(permits_to_forget(6), 3, "6 -> keeps 3, forgets 3");
        assert_eq!(permits_to_forget(4), 2, "4 -> keeps 2, forgets 2");
        assert_eq!(permits_to_forget(2), 1, "2 -> keeps max(1,1)=1, forgets 1");
        assert_eq!(permits_to_forget(1), 0, "1 -> keeps max(1,0)=1, nothing to forget");
        assert_eq!(
            permits_to_forget(0),
            0,
            "0 -> should never happen in practice, but must not overflow (saturating_sub)"
        );
    }
}
