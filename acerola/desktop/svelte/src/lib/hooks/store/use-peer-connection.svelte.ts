import { invoke } from '@tauri-apps/api/core';
import { listen, type UnlistenFn } from '@tauri-apps/api/event';
import { load } from '@tauri-apps/plugin-store';
import { STORE_FILE, STORE_KEYS } from '#lib/constants/store-plugin.ts';
import { NETWORK_COMMANDS } from '#lib/contracts/network/network.commands.ts';
import { NETWORK_EVENTS } from '#lib/contracts/network/network.events.ts';
import type {
	DeviceInfoPayload,
	NetworkStatusPayload,
	PairedPeerPayload,
	RelayInfo
} from '#lib/contracts/network/network.payloads.ts';
import {
	decodeConnectionCode,
	encodeConnectionCode,
	InvalidConnectionCodeError,
	shortId,
	type LocalPeerAddr
} from '#lib/utils/connection-code.util.ts';

export { InvalidConnectionCodeError, shortId } from '#lib/utils/connection-code.util.ts';

const HANDSHAKE_ALPN = 'acerola/handshake/1';

/// Pairing state: local identity (for the QR/code), network status (peers connected via
/// the `network:status` event) and the action of connecting to a peer by pasting a code
/// generated by this same hook on another device.
export function usePeerConnection() {
	let localId = $state<string | undefined>(undefined);
	let localAddr = $state<LocalPeerAddr | undefined>(undefined);
	let localDeviceInfo = $state<DeviceInfoPayload | undefined>(undefined);
	let relayInfo = $state<RelayInfo | undefined>(undefined);
	let status = $state<NetworkStatusPayload | undefined>(undefined);
	let pairedPeers = $state<PairedPeerPayload[]>([]);
	let connecting = $state(false);
	// Local nickname per peer (contact-book style) — exists only on this device, never
	// exchanged over the protocol. Sits on top of the default `deviceName` the peer announces
	// in the handshake, never overwriting it: `peerLabel` uses it only as display priority.
	let peerNicknames = $state<Record<string, string>>({});

	// `network:status` only carries peerId/alpn/device — not the address bytes, which the lib
	// requires again to open a connection on another ALPN (e.g. firing a sync after the
	// initial pairing). We keep each known peer's `addrs` here — filled both when pairing via
	// a pasted code and (mainly) by `loadPairedPeers()`, which is what makes the sync button
	// exist for a peer that isn't connected right now (the protocol connection itself only
	// lasts seconds — see `NetworkServiceApi::paired_peers`).
	const knownAddrs = new Map<string, number[]>();

	let unlistenStatus: UnlistenFn | undefined;
	let unlistenDeviceInfoReceived: UnlistenFn | undefined;
	let unlistenDeviceInfoExchanged: UnlistenFn | undefined;

	// `startListening`/`loadPairedPeers`/etc are async and may keep running after
	// `stopListening` already ran (unmount in the middle of an await) — without this flag, the
	// continuation tries to write to the $state of an already discarded instance
	// (`usePeerConnection()` is always a new instance per mount, so no reset is needed in
	// `startListening`).
	let disposed = false;

	async function loadLocalInfo() {
		const result = await Promise.all([
			invoke<string>(NETWORK_COMMANDS.getLocalId),
			invoke<LocalPeerAddr>(NETWORK_COMMANDS.getLocalAddr),
			invoke<DeviceInfoPayload>(NETWORK_COMMANDS.getLocalDeviceInfo),
			invoke<RelayInfo>(NETWORK_COMMANDS.getRelayInfo)
		]);
		if (disposed) return;
		[localId, localAddr, localDeviceInfo, relayInfo] = result;

		const store = await load(STORE_FILE);
		const savedNicknames = await store.get<Record<string, string>>(STORE_KEYS.peerNicknames);
		if (disposed) return;
		peerNicknames = savedNicknames ?? {};
	}

	async function refreshStatus() {
		await invoke(NETWORK_COMMANDS.getNetworkStatus);
	}

	/// Loads the list of already paired peers (persisted, regardless of an active connection)
	/// and feeds `knownAddrs` with each one's addresses — without this, the sync buttons stay
	/// disabled for any peer that isn't connected at this exact moment.
	async function loadPairedPeers() {
		const result = await invoke<PairedPeerPayload[]>(NETWORK_COMMANDS.getPairedPeers);
		if (disposed) return;
		pairedPeers = result;
		for (const peer of pairedPeers) {
			knownAddrs.set(peer.peerId, peer.addrs);
		}
	}

	/// Handshake finished (on either side, see `NETWORK_EVENTS.deviceInfoReceived` /
	/// `.deviceInfoExchanged`) — just re-queries the current status instead of trying to build
	/// the peer from the event payload (which is only the raw `peerId`, no `device`/`alpn`).
	async function handlePeerHandshake() {
		await Promise.all([refreshStatus(), loadPairedPeers()]);
	}

	async function startListening() {
		unlistenStatus = await listen<NetworkStatusPayload>(NETWORK_EVENTS.status, (event) => {
			status = event.payload;
		});
		unlistenDeviceInfoReceived = await listen(
			NETWORK_EVENTS.deviceInfoReceived,
			handlePeerHandshake
		);
		unlistenDeviceInfoExchanged = await listen(
			NETWORK_EVENTS.deviceInfoExchanged,
			handlePeerHandshake
		);
		await Promise.all([refreshStatus(), loadPairedPeers()]);
	}

	function stopListening() {
		disposed = true;
		unlistenStatus?.();
		unlistenStatus = undefined;
		unlistenDeviceInfoReceived?.();
		unlistenDeviceInfoReceived = undefined;
		unlistenDeviceInfoExchanged?.();
		unlistenDeviceInfoExchanged = undefined;
	}

	/// The code/QR the other device needs to scan or paste to reach us.
	function connectionCode(): string | undefined {
		if (!localAddr) return undefined;
		return encodeConnectionCode(localAddr);
	}

	async function connectWithCode(code: string) {
		const parsed = decodeConnectionCode(code);

		connecting = true;
		try {
			await invoke(NETWORK_COMMANDS.connectToPeer, {
				peerId: parsed.id.id,
				addrs: parsed.addrs,
				alpn: HANDSHAKE_ALPN
			});
			knownAddrs.set(parsed.id.id, parsed.addrs);
			// The handshake already persists this peer in the backend (`save_peer_if_present`) —
			// reload so it shows in the paired list without waiting for the next app restart.
			await Promise.all([refreshStatus(), loadPairedPeers()]);
		} finally {
			connecting = false;
		}
	}

	/// Sets a nickname for the local device (LocalSend style, instead of the automatic
	/// hostname) — applies it right away to the P2P node (the next handshake already uses the
	/// new name, no app restart needed) and persists it in `settings.json` to survive a restart.
	async function setDeviceName(name: string) {
		const trimmed = name.trim();
		if (!trimmed) return;

		await invoke(NETWORK_COMMANDS.setLocalDeviceName, { name: trimmed });
		if (localDeviceInfo) localDeviceInfo = { ...localDeviceInfo, name: trimmed };

		const store = await load(STORE_FILE);
		await store.set(STORE_KEYS.deviceAlias, trimmed);
		await store.save();
	}

	function getKnownAddr(peerId: string): number[] | undefined {
		return knownAddrs.get(peerId);
	}

	/// Unpairs a peer — removes it from the local list immediately (without waiting for a new
	/// `loadPairedPeers()`) and from the known address cache, same pattern as
	/// `SyncViewModel::removePeer` on Android. Doesn't drop an active connection nor block the
	/// peer; if it reconnects later, it goes through the same TOFU flow as a never-seen device.
	async function removePeer(peerId: string) {
		await invoke(NETWORK_COMMANDS.removePairedPeer, { peerId });
		pairedPeers = pairedPeers.filter((peer) => peer.peerId !== peerId);
		knownAddrs.delete(peerId);
		await setPeerNickname(peerId, '');
	}

	/// Sets (or clears, with an empty string) a peer's local nickname — only on this device,
	/// never reaches the protocol. Persists in `settings.json` to survive a restart.
	async function setPeerNickname(peerId: string, nickname: string) {
		const trimmed = nickname.trim();
		const next = { ...peerNicknames };
		if (trimmed) {
			next[peerId] = trimmed;
		} else {
			delete next[peerId];
		}
		peerNicknames = next;

		const store = await load(STORE_FILE);
		await store.set(STORE_KEYS.peerNicknames, next);
		await store.save();
	}

	/// A peer's friendly name — prefers the local nickname (`peerNicknames`, set by the user on
	/// this device), then `network:status` (fresher, covers the rare case of a device renamed
	/// mid session), then `pairedPeers` (persistent, survives the handshake closing — the
	/// common case) and finally the truncated id.
	function peerLabel(peerId: string): string {
		const nickname = peerNicknames[peerId];
		if (nickname) return nickname;
		const liveDevice = status?.peers.find((peer) => peer.peerId === peerId)?.device;
		if (liveDevice) return liveDevice.name;
		const paired = pairedPeers.find((peer) => peer.peerId === peerId);
		return paired?.deviceName ?? shortId(peerId);
	}

	return {
		loadLocalInfo,
		startListening,
		stopListening,
		refreshStatus,
		connectionCode,
		connectWithCode,
		getKnownAddr,
		setDeviceName,
		removePeer,
		setPeerNickname,
		peerLabel,
		get localId() {
			return localId;
		},
		get localDeviceInfo() {
			return localDeviceInfo;
		},
		get relayInfo() {
			return relayInfo;
		},
		get status() {
			return status;
		},
		get pairedPeers() {
			return pairedPeers;
		},
		get peerNicknames() {
			return peerNicknames;
		},
		get connecting() {
			return connecting;
		}
	};
}
