<script lang="ts">
	import { setContext } from 'svelte';
	import AcerolaPrevNextNav from '#lib/components/acerola-prev-next-nav/acerola-prev-next-nav.svelte';
	import { DOC_RAW_CONTEXT_KEY } from '#lib/content/doc-raw-context.ts';
	import { m } from '#lib/paraglide/messages.js';
	import type { PageData } from './$types';

	let { data }: { data: PageData } = $props();

	const Doc = $derived(data.Doc);

	// The raw Markdown isn't part of the frontmatter mdsvex automatically passes to the
	// layout (doc-layout.svelte) — it only exists here, in load()'s return. A getter in
	// context is how this data gets through the `<Doc />` component (generated by mdsvex,
	// outside our control) to the layout, and keeps reading the current value when the user
	// navigates from one doc to another without remounting the page.
	setContext(DOC_RAW_CONTEXT_KEY, {
		get value() {
			return data.raw;
		}
	});
</script>

<svelte:head>
	<title>{data.frontmatter.title} — {m['site.name']()}</title>
	{#if data.frontmatter.description}
		<meta name="description" content={data.frontmatter.description} />
	{/if}
</svelte:head>

<AcerolaPrevNextNav prev={data.prev} next={data.next} position="top" />
<Doc />
<AcerolaPrevNextNav prev={data.prev} next={data.next} />
